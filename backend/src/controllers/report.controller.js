import prisma from '../config/prisma.js';

export const getReports = async (req, res) => {
  try {
    const reports = await prisma.report.findMany({
      orderBy: { generatedAt: 'desc' },
    });
    res.json(reports);
  } catch (error) {
    console.error('Error fetching reports:', error);
    res.status(500).json({ error: 'Failed to retrieve reports list' });
  }
};

export const createReport = async (req, res) => {
  try {
    const { title, type, format, parameters } = req.body;

    if (!title || !type || !format) {
      return res.status(400).json({ error: 'Title, type, and format are required' });
    }

    const userName = req.user ? req.user.name : 'SYSTEM';
    const paramsStr = parameters ? JSON.stringify(parameters) : '{}';

    const report = await prisma.report.create({
      data: {
        title,
        type, // DAILY, WEEKLY, MONTHLY, ANOMALY
        format, // PDF, CSV
        fileUrl: `/api/reports/download/mock-${Date.now()}.${format.toLowerCase()}`,
        generatedBy: userName,
        parameters: paramsStr,
      },
    });

    // Notify activity log
    if (req.user) {
      await prisma.activityLog.create({
        data: {
          userId: req.user.id,
          action: 'GENERATE_REPORT',
          description: `Generated a ${format} ${type} report: "${title}"`,
        },
      });
    }

    res.status(201).json(report);
  } catch (error) {
    console.error('Error generating report:', error);
    res.status(500).json({ error: 'Failed to generate report' });
  }
};

export const downloadReport = async (req, res) => {
  try {
    const { id } = req.params;

    const report = await prisma.report.findUnique({
      where: { id },
    });

    if (!report) {
      return res.status(404).json({ error: 'Report not found' });
    }

    const intersections = await prisma.intersection.findMany({
      include: { Roads: true, Signals: true },
    });

    const timestampStr = new Date().toISOString();

    if (report.format === 'CSV') {
      res.setHeader('Content-Type', 'text/csv');
      res.setHeader('Content-Disposition', `attachment; filename="${report.title.replace(/\s+/g, '_')}.csv"`);

      let csvContent = `Smart City Traffic System Report\n`;
      csvContent += `Title,${report.title}\n`;
      csvContent += `Type,${report.type}\n`;
      csvContent += `Generated By,${report.generatedBy}\n`;
      csvContent += `Generated At,${report.generatedAt}\n\n`;
      
      csvContent += `INTERSECTIONS STATUS DATA\n`;
      csvContent += `ID,Intersection Name,Latitude,Longitude,Status,Congestion Level,Vehicle Count\n`;
      
      intersections.forEach((item) => {
        csvContent += `"${item.id}","${item.name}",${item.latitude},${item.longitude},"${item.status}",${item.congestionLevel.toFixed(2)},${item.vehicleCount}\n`;
      });

      return res.send(csvContent);
    } else {
      // Return a text-based "PDF" simulation that downloads as a text report
      res.setHeader('Content-Type', 'text/plain');
      res.setHeader('Content-Disposition', `attachment; filename="${report.title.replace(/\s+/g, '_')}.pdf"`);

      let pdfSimContent = `========================================================================\n`;
      pdfSimContent += `                  SMART CITY TRAFFIC MANAGEMENT SYSTEM\n`;
      pdfSimContent += `                      OFFICIAL SYSTEM TRANSIT REPORT\n`;
      pdfSimContent += `========================================================================\n\n`;
      pdfSimContent += `REPORT METADATA:\n`;
      pdfSimContent += `------------------------------------------------------------------------\n`;
      pdfSimContent += `Report ID:     ${report.id}\n`;
      pdfSimContent += `Title:         ${report.title}\n`;
      pdfSimContent += `Type:          ${report.type}\n`;
      pdfSimContent += `Format:        PDF (Simulated in plain-text standard output)\n`;
      pdfSimContent += `Generated By:  ${report.generatedBy}\n`;
      pdfSimContent += `Generated At:  ${report.generatedAt}\n`;
      pdfSimContent += `Scope Params:  ${report.parameters}\n\n`;
      
      pdfSimContent += `METROPOLITAN TRAFFIC METRICS SUMMARY:\n`;
      pdfSimContent += `------------------------------------------------------------------------\n`;
      
      intersections.forEach((item) => {
        pdfSimContent += `* INTERSECTION: ${item.name.padEnd(30)} | Status: ${item.status.padEnd(10)} | Traffic Density: ${(item.congestionLevel * 100).toFixed(0)}% | Flow Rate: ${item.vehicleCount} vehicles/hr\n`;
        item.Roads.forEach((road) => {
          pdfSimContent += `    - Roadway: ${road.direction.padEnd(5)} | Approach: ${road.name.padEnd(20)} | Speed: ${road.currentSpeed.toFixed(1)} km/h | Lanes: ${road.laneCount}\n`;
        });
        pdfSimContent += `\n`;
      });
      
      pdfSimContent += `------------------------------------------------------------------------\n`;
      pdfSimContent += `END OF REPORT - TRANSIT INFRASTRUCTURE AUTHORITY CONTROL - SECURE VERIFIED\n`;
      pdfSimContent += `========================================================================\n`;

      return res.send(pdfSimContent);
    }
  } catch (error) {
    console.error('Error downloading report:', error);
    res.status(500).json({ error: 'Failed to download report' });
  }
};
